// Helper to generate realistic candlestick data for charts
export interface CandleData {
  time: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
}

export function generateCandleData(basePrice: number, pointsCount = 40): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice * 0.94;
  const now = new Date();

  for (let i = pointsCount - 1; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    const volatility = currentClose * 0.012;
    const change = (Math.random() - 0.48) * volatility;
    const open = currentClose;
    const close = +(open + change).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * volatility * 0.7).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * volatility * 0.7).toFixed(2);
    const volume = Math.floor(Math.random() * 80000 + 20000);

    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });

    currentClose = close;
  }

  // Ensure last close matches basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }

  return candles;
}
